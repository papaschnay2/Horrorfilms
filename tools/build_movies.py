#!/usr/bin/env python3
"""Turn data/films.json into movies.js.

Run from the repo root:  python3 tools/build_movies.py
"""
import json
from collections import Counter

WHO = "friends family couple woman kids experts crew town filmmakers cops travelers loner other".split()
WHERE = "house cabin camp smalltown suburb city institution school hotel road water remote abroad other".split()
WHAT = "slasher ghost demon zombie vampire werewolf creature alien cult object mind humans curse science other".split()
RELATIONS = {"original", "sequel", "prequel", "remake", "reboot", "spinoff"}


def tidy(text):
    text = (text or "").strip()
    return text[:1].upper() + text[1:] if text else None


def main():
    films = json.load(open("data/films.json", encoding="utf-8"))
    out, seen = [], set()
    for f in films:
        key = (f["title"].lower(), f.get("year"))
        if f.get("skip") or f.get("is_film") is False or key in seen or not f.get("year"):
            continue
        seen.add(key)
        rel = f.get("relation") if f.get("relation") in RELATIONS else None
        tags = list(f.get("tags") or [])
        if rel in ("sequel", "prequel", "remake"):
            tags.append(rel)
        out.append({
            "t": f["title"], "y": f["year"], "d": f.get("director"),
            "wt": tidy(f.get("who_text")), "loc": tidy(f.get("where_text")),
            "th": tidy(f.get("threat_text")), "mk": tidy(f.get("mistake")),
            "who": f.get("who") if f.get("who") in WHO else None,
            "where": f.get("where") if f.get("where") in WHERE else None,
            "what": f.get("what") if f.get("what") in WHAT else None,
            "fr": f.get("franchise"), "rel": rel, "tg": tags,
            "s": f.get("summary"), "u": f.get("url"),
        })
    out.sort(key=lambda m: (m["y"], m["t"]))
    with open("movies.js", "w", encoding="utf-8") as fh:
        fh.write("// Generated by tools/build_movies.py from data/films.json. Edit that file, not this one.\n")
        fh.write("const MOVIES = [\n")
        for m in out:
            fh.write("  " + json.dumps({k: v for k, v in m.items() if v not in (None, [])}, ensure_ascii=False) + ",\n")
        fh.write("];\n")
    full = sum(1 for m in out if m["who"] and m["where"] and m["what"])
    print(f"{len(out)} films, {full} with who, where and what")
    for key in ("who", "where", "what"):
        print(key, dict(Counter(m[key] for m in out if m[key]).most_common()))
    print("franchises", Counter(m["fr"] for m in out if m["fr"]).most_common(12))


if __name__ == "__main__":
    main()
